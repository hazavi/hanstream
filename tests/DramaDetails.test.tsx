import { cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { DramaDetails } from '../components/DramaDetails';
vi.mock('next/link', () => ({ default: ({ prefetch: _prefetch, ...props }: React.ComponentProps<'a'> & {prefetch?:boolean}) => <a {...props}/> }));
vi.mock('next/image', () => ({ default: ({ fill:_fill, priority:_priority, ...props }: React.ComponentProps<'img'> & {fill?:boolean;priority?:boolean}) => <img {...props}/> }));
vi.mock('../components/WatchlistButton', () => ({WatchlistButton:()=>null}));
vi.mock('../components/DramaRatingButton', () => ({DramaRatingButton:()=>null}));
afterEach(cleanup);
const cast = Array.from({length:13}, (_,i)=>({name:`Actor ${i+1}`,character:`Role ${i+1}`}));
it('mounts six cast members per page, recovers photos lazily, and omits rating and show type', () => {
  const {container} = render(<DramaDetails slug="fixture" detail={{ title:'Fixture', cast, meta:{Country:'Korea',Rating:7,'Rating votes':20,'Show Type':'Scripted'}, episodes:[] }}/>);
  expect(screen.getByRole('tab',{name:'Show info'})).toHaveAttribute('aria-selected','true');
  const info=screen.getByRole('region',{name:'Show info'});
  expect(info).toHaveTextContent('Korea');
  expect(info).not.toHaveTextContent(/Community rating|Show Type|Scripted|7\/10/);
  fireEvent.click(screen.getByRole('tab',{name:'Cast'}));
  expect(screen.getAllByRole('heading',{level:3})).toHaveLength(6);
  expect(screen.getByAltText('Actor 1').getAttribute('src')).toContain('/api/portrait?name=Actor+1');
  expect(screen.queryByText('Actor 7')).toBeNull();
  expect(screen.getByText('as Role 1')).toBeInTheDocument();
  expect(screen.getByRole('button',{name:'Previous cast page'})).toBeDisabled();
  fireEvent.click(screen.getByRole('button',{name:'Next cast page'}));
  expect(screen.queryByText('Actor 1')).toBeNull();
  expect(screen.getByText('Actor 7')).toBeInTheDocument();
  expect(screen.getByRole('status')).toHaveTextContent('7–12 of 13');
  fireEvent.click(screen.getByRole('button',{name:'Next cast page'}));
  expect(screen.getAllByRole('heading',{level:3})).toHaveLength(1);
  expect(screen.getByText('Actor 13')).toBeInTheDocument();
  expect(screen.getByRole('button',{name:'Next cast page'})).toBeDisabled();
  expect(screen.queryByRole('tab',{name:'Trailer'})).toBeNull();
  expect(container.querySelector('iframe')).toBeNull();
});
it('uses a poster for placeholder stills and preserves full upcoming episode numbers', () => {
  render(<DramaDetails slug="fixture" detail={{title:'Fixture',image:'https://pictures.example/poster.jpg',episodes:[{episode:5, title:'Released',episode_link:'/fixture/episode/5',image:'https://pictures.example/images/no-img/no-img-landscape-text.png',available:true},...[9,10,11,100].map(episode=>({episode,title:`Episode ${episode}`,available:false,episode_link:`/fixture/episode/${episode}`}))]}}/>);
  expect(screen.getByAltText('Released')).toHaveAttribute('src','https://pictures.example/poster.jpg');
  for(const episode of [9,10,11,100]) expect(screen.getByText(`E${episode}`)).toBeInTheDocument();
  expect(screen.queryByText('E1')).toBeNull();
  expect(screen.getAllByText('Upcoming')).toHaveLength(4);
});
it('switches media tabs by keyboard and unloads the video when returning to cast', () => {
  const {container}=render(<DramaDetails slug="fixture" detail={{title:'Fixture',cast,trailer:{embedUrl:'https://www.youtube-nocookie.com/embed/abcdefghijk'}}}/>);
  fireEvent.keyDown(screen.getByRole('tab',{name:'Cast'}),{key:'ArrowRight'});
  expect(screen.getByRole('tab',{name:'Trailer'})).toHaveAttribute('aria-selected','true');
  fireEvent.click(screen.getByRole('button',{name:'Play official trailer'}));
  expect(container.querySelector('iframe')).toBeInTheDocument();
  fireEvent.click(screen.getByRole('tab',{name:'Cast'}));
  expect(container.querySelector('iframe')).toBeNull();
});
